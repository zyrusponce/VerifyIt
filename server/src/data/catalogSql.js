// Builds the SQL that syncs the trusted catalog (ids, answer keys, expected verdicts) into the
// database's private schema. Used by scripts/generate-catalog-seed.js and by the drift test.
import { lessons } from './lessons.js'
import { investigationCases } from './investigations.js'
import { allQuestions, quizCategories } from './quizzes.js'
import { toolkitItems } from './toolkit.js'

const literal = (value) => {
  if (value === null || value === undefined) return 'null'
  if (typeof value === 'boolean') return value ? 'true' : 'false'
  if (typeof value === 'number') {
    if (!Number.isInteger(value)) throw new TypeError(`Expected an integer, received ${value}`)
    return String(value)
  }
  return `'${String(value).replaceAll("'", "''")}'`
}

function upsert(table, columns, rows, updateColumns) {
  const values = rows.map((row) => `  (${row.map(literal).join(', ')})`).join(',\n')
  const updates = updateColumns.map((column) => `${column} = excluded.${column}`).join(', ')
  return `insert into ${table} (${columns.join(', ')}) values\n${values}\non conflict (id) do update set ${updates};`
}

function deactivateMissing(table, ids) {
  return `update ${table} set active = false where id not in (${ids.map(literal).join(', ')});`
}

export function buildCatalogSyncSql() {
  const sections = [
    `-- GENERATED by \`npm run catalog:seed --prefix server\` from the server catalog. Do not edit by hand.
-- Syncs the trusted catalog into the private schema: ids, titles, quiz answer keys, and expected
-- investigation verdicts. Items removed from the catalog are deactivated rather than deleted so that
-- existing progress keeps its references; inactive items never count toward certificates.`,

    upsert(
      'private.lessons',
      ['id', 'title', 'sort_order', 'required_for_certificate', 'active'],
      lessons.map((l) => [l.id, l.title, l.sortOrder, l.requiredForCertificate, true]),
      ['title', 'sort_order', 'required_for_certificate', 'active'],
    ),
    deactivateMissing('private.lessons', lessons.map((l) => l.id)),

    upsert(
      'private.investigation_cases',
      ['id', 'title', 'expected_verdict', 'sort_order', 'required_for_certificate', 'active'],
      investigationCases.map((c) => [c.id, c.title, c.expected, c.sortOrder, c.requiredForCertificate, true]),
      ['title', 'expected_verdict', 'sort_order', 'required_for_certificate', 'active'],
    ),
    deactivateMissing('private.investigation_cases', investigationCases.map((c) => c.id)),

    upsert(
      'private.quiz_categories',
      ['id', 'title', 'is_mixed', 'questions_per_category', 'sort_order', 'active'],
      quizCategories.map((c) => [c.id, c.title, c.isMixed, c.questionsPerCategory, c.sortOrder, true]),
      ['title', 'is_mixed', 'questions_per_category', 'sort_order', 'active'],
    ),
    deactivateMissing('private.quiz_categories', quizCategories.map((c) => c.id)),

    upsert(
      'private.quiz_questions',
      ['id', 'category_id', 'option_count', 'correct_option', 'active'],
      allQuestions.map((q) => [q.id, q.categoryId, q.options.length, q.answer, true]),
      ['category_id', 'option_count', 'correct_option', 'active'],
    ),
    deactivateMissing('private.quiz_questions', allQuestions.map((q) => q.id)),

    upsert(
      'private.toolkit_items',
      ['id', 'sort_order', 'active'],
      toolkitItems.map((item) => [item.id, item.sortOrder, true]),
      ['sort_order', 'active'],
    ),
    deactivateMissing('private.toolkit_items', toolkitItems.map((item) => item.id)),
  ]
  return `${sections.join('\n\n')}\n`
}
